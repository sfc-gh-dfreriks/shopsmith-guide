-- Snowflake objects for the Shopsmith Part ID app (Streamlit in Snowflake + Cortex AI_COMPLETE vision).
-- Run as a role that can create databases, warehouses and Streamlit apps.

CREATE DATABASE IF NOT EXISTS SHOPSMITH_GUIDE;
CREATE SCHEMA IF NOT EXISTS SHOPSMITH_GUIDE.APP;

-- Photos must be on a server-side-encrypted stage for TO_FILE / AI_COMPLETE.
CREATE STAGE IF NOT EXISTS SHOPSMITH_GUIDE.APP.PHOTOS
  DIRECTORY = (ENABLE = TRUE) ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE');
CREATE STAGE IF NOT EXISTS SHOPSMITH_GUIDE.APP.APP_SRC;

CREATE WAREHOUSE IF NOT EXISTS SHOPSMITH_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

-- Upload the catalog first (data/parts.json converted to one JSON object per line):
--   PUT file://parts.jsonl @SHOPSMITH_GUIDE.APP.APP_SRC/data AUTO_COMPRESS=FALSE OVERWRITE=TRUE;
CREATE OR REPLACE FILE FORMAT SHOPSMITH_GUIDE.APP.JSONL TYPE = JSON;
CREATE OR REPLACE TABLE SHOPSMITH_GUIDE.APP.PARTS AS
SELECT $1:id::STRING ID, $1:name::STRING NAME, $1:category::STRING CATEGORY, $1:visual::STRING VISUAL,
       $1:mount::STRING MOUNT, $1:use::STRING USE_TEXT, $1:guide_section::STRING GUIDE_SECTION,
       $1:part_numbers PART_NUMBERS, $1:used_in USED_IN, $1:refs REFS
FROM @SHOPSMITH_GUIDE.APP.APP_SRC/data/parts.jsonl (FILE_FORMAT => 'SHOPSMITH_GUIDE.APP.JSONL');

-- Upload streamlit/streamlit_app.py and streamlit/environment.yml to @SHOPSMITH_GUIDE.APP.APP_SRC/streamlit, then:
CREATE OR REPLACE STREAMLIT SHOPSMITH_GUIDE.APP.PART_ID
  FROM '@SHOPSMITH_GUIDE.APP.APP_SRC/streamlit'
  MAIN_FILE = 'streamlit_app.py'
  QUERY_WAREHOUSE = SHOPSMITH_WH
  TITLE = 'Shopsmith Part ID';
ALTER STREAMLIT SHOPSMITH_GUIDE.APP.PART_ID ADD LIVE VERSION FROM LAST;
